// ===== Документ справки: общий TextBuffer =====

/// Пишет контент в один TextBuffer: и на экран, и в буфер копирования
/// (plain-текст = `buffer.text()`, теги в него не попадают).
struct HelpDoc {
    buf: TextBuffer,
}

impl HelpDoc {
    fn new(buf: TextBuffer) -> Self {
        Self { buf }
    }

    /// Возвращает накопленный plain-текст (для «Копировать всю справку»).
    fn finish(&self) -> String {
        self.buf
            .text(&self.buf.start_iter(), &self.buf.end_iter(), false)
            .to_string()
    }

    /// Вставляет текст с тегами + перевод строки.
    fn insert(&mut self, text: &str, tags: &[&str]) {
        let mut iter = self.buf.end_iter();
        self.buf.insert_with_tags_by_name(&mut iter, text, tags);
        let mut nl = self.buf.end_iter();
        self.buf.insert(&mut nl, "\n");
    }

    /// Заголовок раздела (крупный).
    fn h1(&mut self, text: &str) {
        self.insert(text, &["h1"]);
    }

    /// Подзаголовок раздела.
    fn h2(&mut self, text: &str) {
        self.insert(text, &["h2"]);
    }

    /// Под-подзаголовок.
    fn h3(&mut self, text: &str) {
        self.insert(text, &["h3"]);
    }

    /// Абзац.
    fn p(&mut self, text: &str) {
        self.insert(text, &[]);
    }

    /// Маркированный список.
    fn bullets(&mut self, items: &[&str]) {
        for it in items {
            self.insert(&format!("• {it}"), &["bullet"]);
        }
    }

    /// Примечание (серый курсив).
    fn note(&mut self, text: &str) {
        self.insert(text, &["note"]);
    }

    /// Вопрос-ответ.
    fn faq(&mut self, q: &str, a: &str) {
        self.insert(&format!("• {q}"), &["h3"]);
        self.insert(a, &["bullet"]);
    }
}

/// Строки раздела «Отчёты и их расположение в ЛК» по маркетплейсам:
/// «Имя — путь в ЛК» («—» = документация путь не указывает). Чистая функция
/// от дескрипторов провайдеров — раздел всегда актуален, тест сверяет полноту.
pub(crate) fn reports_lk_sections() -> Vec<(&'static str, Vec<String>)> {
    [
        ("Ozon", mdwf_providers_ozon::all_report_descriptors()),
        ("Wildberries", mdwf_providers_wildberries::all_report_descriptors()),
    ]
    .into_iter()
    .map(|(mp, descs)| {
        let lines = descs
            .iter()
            .map(|d| {
                format!(
                    "{} — {}",
                    d.display_name,
                    d.cabinet_path.as_deref().unwrap_or("—")
                )
            })
            .collect();
        (mp, lines)
    })
    .collect()
}

// Подавление unused-import предупреждения для glib (нужен trait-ам виджетов).
#[allow(unused_imports)]
use glib as _glib;

#[cfg(test)]
mod lk_tests {
    use super::reports_lk_sections;

    #[test]
    fn help_lists_all_reports_with_cabinet() {
        let sections = reports_lk_sections();
        // Оба маркетплейса, все отчёты (21 Ozon + 13 WB), у каждой строки
        // формат «Имя — путь» (путь может быть «—»).
        let counts: Vec<(usize, usize)> = sections
            .iter()
            .map(|(mp, lines)| {
                assert!(!lines.is_empty(), "{mp}: пусто");
                for l in lines {
                    assert!(l.contains(" — "), "нет разделителя: {l}");
                }
                (lines.len(), lines.iter().filter(|l| !l.ends_with('—')).count())
            })
            .collect();
        assert_eq!(counts[0].0, 21, "Ozon: должно быть 21 отчёт");
        assert_eq!(counts[1].0, 13, "WB: должно быть 13 отчётов");
        // У большинства путь известен (None только у 3 Ozon-отчётов).
        assert!(counts[0].1 >= 18, "Ozon: ЛК-пути менее 18: {}", counts[0].1);
        assert!(counts[1].1 >= 13, "WB: ЛК-пути менее 13: {}", counts[1].1);
    }
}
