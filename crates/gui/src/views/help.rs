//! Вкладка «Справка»: подробная помощь по программе для пользователей.
//!
//! Весь текст живёт в ОДНОМ `gtk4::TextView` (неотредактируемом, но выделяемом):
//! выделение мышью работает сквозь весь документ (не обрывается на границе
//! абзаца, как у отдельных Label'ов), Ctrl+A выделяет всё, Ctrl+C копирует.
//! Заголовки/курсив/отступы — TextTag'и; кнопка «Копировать всю справку»
//! кладёт в буфер обмена текст целиком.
//!
//! Разделы: обзор, быстрый старт, каждая вкладка, хранение данных, частые
//! вопросы. Self-contained (без внешних файлов), работает в relocatable-бандле.

use gtk4::glib;
use gtk4::prelude::*;
use gtk4::{PolicyType, ScrolledWindow, TextBuffer, TextTag, TextView};

/// Строит вкладку «Справка».
#[must_use]
pub fn build() -> gtk4::Widget {
    let root = gtk4::Box::builder()
        .orientation(gtk4::Orientation::Vertical)
        .build();

    let buf = TextBuffer::new(None);
    make_tags(&buf);
    let mut doc = HelpDoc::new(buf.clone());
    fill_content(&mut doc);
    let plain_text = doc.finish();

    // --- Верхняя полоса: кнопка «Копировать всю справку» + подтверждение ---
    let bar = gtk4::Box::builder()
        .orientation(gtk4::Orientation::Horizontal)
        .spacing(8)
        .margin_top(12)
        .margin_start(24)
        .margin_end(24)
        .build();
    let copy_btn = super::icon_button("Копировать всю справку", "edit-copy-symbolic");
    copy_btn.set_tooltip_text(Some(
        "Кладёт весь текст справки в буфер обмена (для вставки в документ).\n\
         Или выделите фрагмент в тексте ниже и нажмите Ctrl+C (Ctrl+A — весь текст).",
    ));
    let copied_lbl = gtk4::Label::new(Some("Скопировано ✓"));
    copied_lbl.set_css_classes(&["success"]);
    copied_lbl.set_visible(false);
    {
        let text = plain_text;
        let lbl = copied_lbl.clone();
        copy_btn.connect_clicked(move |_| {
            if let Some(d) = gtk4::gdk::Display::default() {
                d.clipboard().set_text(&text);
                lbl.set_visible(true);
                let lbl2 = lbl.clone();
                glib::source::timeout_add_local_once(std::time::Duration::from_secs(2), move || {
                    lbl2.set_visible(false);
                });
            }
        });
    }
    bar.append(&copy_btn);
    bar.append(&copied_lbl);
    root.append(&bar);

    // --- Текст справки: один TextView (единое выделение) ---
    let view = TextView::with_buffer(&buf);
    view.set_editable(false);
    view.set_cursor_visible(false);
    view.set_wrap_mode(gtk4::WrapMode::Word);
    view.set_left_margin(24);
    view.set_right_margin(24);
    view.set_top_margin(8);
    view.set_bottom_margin(24);

    let scroll = ScrolledWindow::builder()
        .hscrollbar_policy(PolicyType::Never)
        .vexpand(true)
        .build();
    scroll.set_child(Some(&view));
    root.append(&scroll);
    root.upcast::<gtk4::Widget>()
}

/// Теги оформления. Отступы между блоками — pixels_above/below_lines у тега
/// (не пустые строки), чтобы скопированный текст оставался чистым.
fn make_tags(buf: &TextBuffer) {
    let table = buf.tag_table();

    let h1 = TextTag::new(Some("h1"));
    h1.set_weight(700); // PANGO_WEIGHT_BOLD
    h1.set_scale(1.6);
    h1.set_pixels_below_lines(10);
    table.add(&h1);

    let h2 = TextTag::new(Some("h2"));
    h2.set_weight(700); // PANGO_WEIGHT_BOLD
    h2.set_scale(1.2);
    h2.set_pixels_above_lines(18);
    h2.set_pixels_below_lines(4);
    table.add(&h2);

    let h3 = TextTag::new(Some("h3"));
    h3.set_weight(700); // PANGO_WEIGHT_BOLD
    h3.set_pixels_above_lines(8);
    table.add(&h3);

    let bullet = TextTag::new(Some("bullet"));
    bullet.set_left_margin(24);
    table.add(&bullet);

    let note = TextTag::new(Some("note"));
    note.set_style(gtk4::pango::Style::Italic);
    note.set_left_margin(24);
    note.set_foreground_rgba(Some(&gtk4::gdk::RGBA::new(0.5, 0.5, 0.5, 1.0)));
    table.add(&note);
}

