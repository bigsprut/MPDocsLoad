// ===== Хелперы разметки =====

/// Label с Pango-разметкой, переносом по словам и выравниванием влево.
fn mlabel(markup: &str) -> Label {
    let l = Label::new(None);
    l.set_wrap(true);
    l.set_xalign(0.0);
    l.set_halign(Align::Start);
    l.set_hexpand(true);
    l.set_markup(markup);
    l
}

/// Заголовок раздела (крупный).
fn h1(col: &gtk4::Box, text: &str) {
    let l = mlabel(&format!("<span size=\"xx-large\" weight=\"bold\">{text}</span>"));
    l.set_margin_bottom(8);
    col.append(&l);
}

/// Подзаголовок раздела.
fn h2(col: &gtk4::Box, text: &str) {
    let l = mlabel(&format!("<span size=\"large\" weight=\"bold\">{text}</span>"));
    l.set_margin_top(16);
    l.set_margin_bottom(4);
    col.append(&l);
}

/// Под-подзаголовок.
fn h3(col: &gtk4::Box, text: &str) {
    let l = mlabel(&format!("<b>{text}</b>"));
    l.set_margin_top(8);
    col.append(&l);
}

/// Абзац (с Pango-разметкой).
fn p(col: &gtk4::Box, text: &str) {
    col.append(&mlabel(text));
}

/// Маркированный список.
fn bullets(col: &gtk4::Box, items: &[&str]) {
    for it in items {
        let l = mlabel(&format!("• {it}"));
        l.set_margin_start(12);
        col.append(&l);
    }
}

/// Примечание (серый курсив).
fn note(col: &gtk4::Box, text: &str) {
    let l = mlabel(&format!("<i>{text}</i>"));
    l.set_margin_start(12);
    l.set_margin_top(4);
    l.add_css_class("dim-label");
    col.append(&l);
}

/// Вопрос-ответ.
fn faq(col: &gtk4::Box, q: &str, a: &str) {
    let q1 = mlabel(&format!("<b>• {q}</b>"));
    q1.set_margin_top(6);
    col.append(&q1);
    let a1 = mlabel(a);
    a1.set_margin_start(12);
    col.append(&a1);
}

